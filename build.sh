#!/usr/bin/env bash
# Builds the Android app (WebCam.apk) without Gradle, using only Android SDK build-tools + JDK.
#
# Version comes from ./VERSION (x.y.z). Signing:
#   KEYSTORE / KEYSTORE_PASS / KEY_ALIAS env vars, or
#   ~/.android/pocketlens-release.jks + ~/.android/pocketlens-release.pass (release key), or
#   ~/.android/debug.keystore (fallback; created if missing)
set -euo pipefail
cd "$(dirname "$0")"

SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/Android/Sdk}}"
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
PLAT="$SDK/platforms/$(ls "$SDK/platforms" | grep -E '^android-[0-9]+$' | sort -V | tail -1)/android.jar"
OUT=build

VERSION="$(tr -d ' \n\r' < VERSION)"
IFS=. read -r MAJ MIN PAT <<< "$VERSION"
VCODE=$((MAJ * 10000 + MIN * 100 + PAT))
REPO="$(tr -d ' \n\r' < REPO 2>/dev/null || echo "")"

REL_KS="$HOME/.android/pocketlens-release.jks"
if [ -n "${KEYSTORE:-}" ]; then
  KS="$KEYSTORE"; KSPASS="${KEYSTORE_PASS:?KEYSTORE_PASS required}"; ALIAS="${KEY_ALIAS:-pocketlens}"
elif [ -f "$REL_KS" ]; then
  KS="$REL_KS"; KSPASS="$(cat "$HOME/.android/pocketlens-release.pass")"; ALIAS=pocketlens
else
  KS="$HOME/.android/debug.keystore"; KSPASS=android; ALIAS=androiddebugkey
  if [ ! -f "$KS" ]; then
    keytool -genkeypair -keystore "$KS" -storepass android -keypass android -alias androiddebugkey \
      -dname "CN=Android Debug,O=Android,C=US" -keyalg RSA -keysize 2048 -validity 10000
  fi
  echo "Aviso: firmando con debug.keystore (no apto para releases)." >&2
fi

rm -rf "$OUT"
mkdir -p "$OUT/classes" "$OUT/dex" "$OUT/gen/com/webcam/adb"

cat > "$OUT/gen/com/webcam/adb/BuildInfo.java" <<EOF
package com.webcam.adb;
/** Generated by build.sh */
final class BuildInfo {
    static final String VERSION = "$VERSION";
    static final int VERSION_CODE = $VCODE;
    static final String REPO = "$REPO";
    private BuildInfo() { }
}
EOF

"$BT/aapt2" compile --dir android/res -o "$OUT/res.zip"
"$BT/aapt2" link -o "$OUT/base.apk" -I "$PLAT" \
  --manifest android/AndroidManifest.xml \
  -R "$OUT/res.zip" --java "$OUT/gen" --auto-add-overlay \
  --min-sdk-version 24 --target-sdk-version 34 \
  --version-code "$VCODE" --version-name "$VERSION"

javac -nowarn --release 11 -classpath "$PLAT" \
  -d "$OUT/classes" $(find android/src "$OUT/gen" -name '*.java')

"$BT/d8" --release --min-api 24 --lib "$PLAT" --output "$OUT/dex" \
  $(find "$OUT/classes" -name '*.class')

cp "$OUT/base.apk" "$OUT/unsigned.apk"
(cd "$OUT/dex" && zip -q -j ../unsigned.apk classes.dex)
"$BT/zipalign" -f 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"

"$BT/apksigner" sign --ks "$KS" --ks-pass "pass:$KSPASS" --key-pass "pass:${KEY_PASS:-$KSPASS}" \
  --ks-key-alias "$ALIAS" --out WebCam.apk "$OUT/aligned.apk"
rm -f WebCam.apk.idsig

echo "OK -> $(pwd)/WebCam.apk  (v$VERSION, code $VCODE)"
